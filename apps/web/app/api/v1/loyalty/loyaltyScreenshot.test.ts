type Who = EnrolledUser | { bearer: string } | null;
interface Answer { status: number; text: string; body: { success?: boolean; data?: Record<string, unknown>; error?: { code: string; message: string } } }
const auth = (who: Who) => (who === null ? {} : 'bearer' in who ? bearer(who.bearer) : cookie(who.token));
async function answerOf(res: Response | Promise<Response>): Promise<Answer> {
  const r = await res;
  const text = await r.text();
  let body: Answer['body'] = {};
  try { body = JSON.parse(text); } catch { /* not JSON */ }
  heard.push(text);
  return { status: r.status, text, body };
}
const ctx = (id: number | string) => ({ params: Promise.resolve({ id: String(id) }) });
function readAs(who: Who, id: number | string, body: Uint8Array | ReadableStream<Uint8Array>, type = 'image/jpeg') {
  const init = {
    method: 'POST', headers: { host: 'localhost:3000', 'content-type': type, ...auth(who) }, body,
    ...(body instanceof ReadableStream ? { duplex: 'half' } : {}),
  };
  return answerOf(readPOST(new NextRequest(`${ORIGIN}/api/v1/loyalty/memberships/${id}/screenshot`, init as ConstructorParameters<typeof NextRequest>[1]), ctx(id)));
}
const jsonInit = (who: Who, body: unknown) => ({ method: 'POST', headers: { host: 'localhost:3000', 'content-type': 'application/json', ...auth(who) }, body: JSON.stringify(body) });
const confirmAs = (who: Who, id: number | string, body: unknown) =>
  answerOf(confirmPOST(new NextRequest(`${ORIGIN}/api/v1/loyalty/memberships/${id}/screenshot/confirm`, jsonInit(who, body)), ctx(id)));
const typedAs = (who: Who, id: number, body: unknown) =>
  answerOf(typedPOST(new NextRequest(`${ORIGIN}/api/v1/loyalty/memberships/${id}/observations`, jsonInit(who, body)), ctx(id)));
async function overview(who: EnrolledUser = owner) {
  const a = await answerOf(overviewGET(new NextRequest(`${ORIGIN}/api/v1/loyalty`, { headers: { host: 'localhost:3000', ...auth(who) } })));
  const data = a.body.data as { inboxRead: { screenshotDue: number[] }; cards: { memberships: Record<string, unknown>[] }[] };
  return { due: data.inboxRead.screenshotDue, view: (id: number) => data.cards.flatMap((c) => c.memberships).find((m) => m.id === id) };
}

