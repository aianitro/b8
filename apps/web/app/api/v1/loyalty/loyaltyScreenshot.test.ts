const withSignature = (sig: number[], size = 64) => {
  const b = new Uint8Array(size);
  b.set(sig);
  for (let i = sig.length; i < size; i++) b[i] = (i * 7) % 251;
  return b;
};
const JPEG = [0xff, 0xd8, 0xff, 0xe0];
const PNG = [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a];
const WEBP = [0x52, 0x49, 0x46, 0x46, 0, 0, 0, 0, 0x57, 0x45, 0x42, 0x50];
const jpeg = () => withSignature(JPEG);
const SENT = 'ZQ42D-SENT-BEFORE-THE-ERROR';

/** A body stream: `error` makes it fail after a first chunk; `pulled` says whether anything read it. */
function streamOf(bytes: Uint8Array, error: boolean) {
  const flag = { pulled: false };
  let sent = false;
  const stream = new ReadableStream<Uint8Array>({
    pull(controller) {
      flag.pulled = true;
      if (!sent) { sent = true; controller.enqueue(error ? new TextEncoder().encode(SENT) : bytes); return; }
      if (error) controller.error(new Error('zq42d body stream failed'));
      else controller.close();
    },
  }, { highWaterMark: 0 });
  return { stream, flag };
}

